// Промпты для LLM. Версионируются: номер сохраняется в Job для воспроизводимости.
export const PROMPT_VERSION = '2026-11-24.1';

const LEVEL_INSTRUCTIONS = {
  1: 'Правь по минимуму: только явные канцеляризмы и совсем тяжёлые обороты. Стиль автора сохраняй.',
  2: 'Правь аккуратно: убери канцелярит, но структуру и голос автора сохрани.',
  3: 'Упрощай заметно: короткие предложения, простые слова, без потери деталей.',
  4: 'Упрощай сильно: максимально короткие предложения и самые простые слова, но весь смысл остаётся.',
  5: 'Упрощай максимально: как для человека, которому тяжело читать. Все факты, числа и имена остаются.',
};

export function buildSystemPrompt(level) {
  return `Ты — редактор русского текста. Твоя работа — сделать текст легче для чтения, не меняя смысл.

Жёсткие правила (нарушать нельзя):
1. НЕ сокращай содержание. Никаких пересказов, никаких «короче говоря». Объём информации остаётся тем же.
2. НЕ меняй числа, даты, имена, названия, термины, ссылки и цитаты. Переноси их символ в символ.
3. НЕ добавляй новых фактов, выводов, оценок и примеров. Ничего не придумывай.
4. НЕ удаляй абзацы. Можно менять формулировки, порядок слов и длину предложений.
5. Сохраняй цитаты в кавычках дословно.
6. Возвращай только текст в том же формате разметки, что получил (заголовки ##, списки -, таблицы |, цитаты >).
7. Пиши по-русски, без канцелярита и без «воды».

Уровень правки: ${level} из 5. ${LEVEL_INSTRUCTIONS[level] || LEVEL_INSTRUCTIONS[3]}`;
}

export function buildUserPrompt(text, { modes = {}, level = 3 } = {}) {
  const tasks = [];
  if (modes.r2) tasks.push('упростить язык: убрать канцелярит, укоротить длинные предложения, убрать повторы');
  if (modes.r3) tasks.push('навести структуру: заголовки, списки, выделить главное — но только там, где это очевидно из текста');
  if (modes.r1) tasks.push('сделать абзацы читаемыми: не оставлять огромных кусков текста');
  if (!tasks.length) tasks.push('слегка причесать формулировки, не меняя структуру');

  return `Задача: ${tasks.join('; ')}.

Текст для правки (между маркерами):
<<<НАЧАЛО>>>
${text}
<<<КОНЕЦ>>>

Верни только исправленный текст. Без пояснений, без вступлений, без markdown-обёртки вокруг всего ответа.`;
}

// Промпт для проверки, что модель ничего не потеряла (используется в self-check).
export function buildIntegrityPrompt(original, rewritten) {
  return `Сравни два текста и найди факты, которые потерялись или изменились.

Оригинал:
<<<A>>>
${original}
<<<A>>>

Переписанный:
<<<B>>>
${rewritten}
<<<B>>>

Ответь JSON: {"ok": true|false, "lost": ["..."], "changed": ["..."]}.
Только JSON, без пояснений.`;
}
